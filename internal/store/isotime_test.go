package store

import (
	"testing"
	"time"
)

func TestParseISOTime(t *testing.T) {
	ny, err := time.LoadLocation("America/New_York")
	if err != nil {
		t.Fatal(err)
	}
	ms := func(s string) int64 {
		at, err := time.Parse(time.RFC3339Nano, s)
		if err != nil {
			t.Fatal(err)
		}
		return at.UnixMilli()
	}
	tests := []struct {
		in   string
		want int64 // 0: not a date
	}{
		{"2026-03-05", ms("2026-03-05T05:00:00Z")},
		{"2026-03-05T09:30", ms("2026-03-05T14:30:00Z")},
		{"2026-03-05 09:30", ms("2026-03-05T14:30:00Z")},
		{"2026-03-05T09:30:15", ms("2026-03-05T14:30:15Z")},
		{"2026-03-05T09:30:15.5", ms("2026-03-05T14:30:15.5Z")},
		{"2026-03-05T09:30:15.123", ms("2026-03-05T14:30:15.123Z")},
		{"2026-03-05T09:30:15.123999999", ms("2026-03-05T14:30:15.123Z")},
		{"2026-03-05T09:30Z", ms("2026-03-05T09:30:00Z")},
		{"2026-03-05T09:30:00+02:00", ms("2026-03-05T07:30:00Z")},
		{"2026-03-05 09:30:00-05:00", ms("2026-03-05T14:30:00Z")},
		{"2026-03-09T09:30", ms("2026-03-09T13:30:00Z")}, // after the clock change: UTC-4
		{"2024-02-29", ms("2024-02-29T05:00:00Z")},
		{"", 0}, {"2026", 0}, {"2026-3-5", 0}, {"2026-03-5", 0}, {"26-03-05", 0}, {"2026/03/05", 0},
		{"2026-13-01", 0}, {"2026-00-01", 0}, {"2026-03-00", 0}, {"2026-02-29", 0}, {"2026-04-31", 0},
		{"2026-03-05T", 0}, {"2026-03-05T09", 0}, {"2026-03-05T9:30", 0}, {"2026-03-05T24:00", 0},
		{"2026-03-05T09:60", 0}, {"2026-03-05T09:30:60", 0}, {"2026-03-05T09:30:", 0}, {"2026-03-05T09:30:15.", 0},
		{"2026-03-05T09:30:15.1234567890", 0}, {"2026-03-05Z", 0}, {"2026-03-05+02:00", 0},
		{"2026-03-05T09:30+2:00", 0}, {"2026-03-05T09:30+24:00", 0}, {"2026-03-05T09:30+02:60", 0},
		{"2026-03-05T09:30 ", 0}, {" 2026-03-05", 0}, {"2026-03-05x", 0}, {"2026-03-05T09:30Zx", 0},
		{"2026-03-05 T09:30", 0}, {"2026-03-05t09:30", 0}, {"2026-03-05T09:30z", 0}, {"２０２６-03-05", 0},
	}
	for _, tc := range tests {
		got, ok := ParseISOTime(tc.in, ny)
		if ok != (tc.want != 0) || got != tc.want {
			t.Errorf("ParseISOTime(%q) = %d, %v; want %d", tc.in, got, ok, tc.want)
		}
	}
}
